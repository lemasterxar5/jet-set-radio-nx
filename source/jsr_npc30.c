int jsr_npc30_validate(so_module *module) {
  if (module->state != SO_STAGED)
    return 0;
  for (unsigned index = 0; index < sizeof g_profiles / sizeof g_profiles[0]; index++) {
    uintptr_t offset = g_profiles[index].offset;
    if (offset > module->load_size || module->load_size - offset < 8 ||
        memcmp((uint8_t *)module->load_base + offset, g_profiles[index].prefix, 8))
      return 0;
  }
  return 1;
}

void jsr_npc30_install(so_module *module) {
  g_base = (uintptr_t)module->load_virtbase;
  g_installed = 1;
  debugPrintf("[npc30] %u enemy controllers/actions use original 30 Hz logic; player adapters unchanged\n",
              (unsigned)(sizeof g_profiles / sizeof g_profiles[0]));
}

int jsr_npc30_handles(void (*callback)(void *)) {
  if (!g_installed)
    return 0;
  for (unsigned index = 0; index < sizeof g_profiles / sizeof g_profiles[0]; index++)
    if ((uintptr_t)callback == g_base + g_profiles[index].offset + 1)
      return 1;
  return 0;
}

int jsr_npc30_dispatch(void *object, void (*callback)(void *), unsigned ticks) {
  if (!jsr_npc30_handles(callback))
    return 0;
  uint32_t flags;
  memcpy(&flags, object, sizeof flags);
  if (flags & 1) {
    jsr_collision60_forget(object);
    return 1;
  }
  if (ticks) {
    jsr_collision60_prepare_npc(object);
    jsr_collision60_begin_npc(object);
    callback(object);
    jsr_collision60_end();
  } else {
    jsr_collision60_hold(object);
  }
  return 1;
}

